// Command gencli derives Porcupine CLI commands from the management OpenAPI.
package main

import (
	"bytes"
	"flag"
	"fmt"
	"go/format"
	"log"
	"maps"
	"os"
	"regexp"
	"slices"
	"sort"
	"strings"

	"github.com/danielgtaylor/huma/v2"
	"github.com/olup/porcupine/internal/porcupine"
)

func main() {
	output := flag.String("o", "cli/cmd/porcupine/operations_gen.go", "output Go source")
	check := flag.Bool("check", false, "fail if the generated file is out of date")
	flag.Parse()
	log.SetFlags(0)
	data, err := generate(porcupine.ManagementOpenAPI())
	if err != nil {
		log.Fatal(err)
	}
	if *check {
		current, err := os.ReadFile(*output)
		if err != nil {
			log.Fatal(err)
		}
		if !bytes.Equal(current, data) {
			log.Fatalf("%s is stale; run go run ./internal/cmd/gencli", *output)
		}
		return
	}
	if err := os.WriteFile(*output, data, 0644); err != nil {
		log.Fatal(err)
	}
}

var commandName = regexp.MustCompile("^[a-z0-9]+(-[a-z0-9]+)*$")

func generate(api *huma.OpenAPI) ([]byte, error) {
	operations := map[string]*huma.Operation{}
	for path, item := range api.Paths {
		if item.Ref != "" || len(item.Parameters) > 0 {
			return nil, fmt.Errorf("%s: path-level references and parameters are unsupported", path)
		}
		for _, op := range []*huma.Operation{item.Get, item.Put, item.Post, item.Delete, item.Options, item.Head, item.Patch, item.Trace} {
			if op == nil {
				continue
			}
			if !commandName.MatchString(op.OperationID) || op.Method == "" || op.Path != path {
				return nil, fmt.Errorf("%s: invalid CLI operation %q", path, op.OperationID)
			}
			if operations[op.OperationID] != nil {
				return nil, fmt.Errorf("duplicate operationId %q", op.OperationID)
			}
			operations[op.OperationID] = op
		}
	}
	var out bytes.Buffer
	out.WriteString("// Code generated by go run ./internal/cmd/gencli. DO NOT EDIT.\n\npackage main\n\nvar operations = []operation{\n")
	for _, id := range slices.Sorted(maps.Keys(operations)) {
		if err := writeOperation(&out, api, operations[id]); err != nil {
			return nil, fmt.Errorf("%s: %w", id, err)
		}
	}
	out.WriteString("}\n")
	return format.Source(out.Bytes())
}

func writeOperation(out *bytes.Buffer, api *huma.OpenAPI, op *huma.Operation) error {
	fmt.Fprintf(out, "{\nID: %q, Method: %q, Path: %q,\nSummary: %q,\n", op.OperationID, op.Method, op.Path, op.Summary)
	if len(op.Parameters) > 0 {
		out.WriteString("Params: []parameter{\n")
		params := slices.Clone(op.Parameters)
		sort.Slice(params, func(i, j int) bool {
			if params[i].In == params[j].In {
				return params[i].Name < params[j].Name
			}
			return params[i].In < params[j].In
		})
		for _, p := range params {
			if err := writeParameter(out, p); err != nil {
				return err
			}
		}
		out.WriteString("},\n")
	}
	if body := op.RequestBody; body != nil {
		if body.Ref != "" || len(body.Content) != 1 {
			return fmt.Errorf("expected a single inline request body content type")
		}
		for media, content := range body.Content {
			fmt.Fprintf(out, "ContentType: %q, BodyRequired: %t,\n", media, body.Required)
			switch media {
			case "application/octet-stream":
			case "application/json":
				if err := writeBodyFields(out, api, content.Schema); err != nil {
					return err
				}
			default:
				return fmt.Errorf("unsupported request media type %q", media)
			}
		}
	}
	out.WriteString("},\n")
	return nil
}

func writeParameter(out *bytes.Buffer, p *huma.Param) error {
	switch p.In {
	case "path", "header", "query":
	default:
		return fmt.Errorf("unsupported parameter location %q for %q", p.In, p.Name)
	}
	if p.Ref != "" || p.Schema == nil || p.AllowReserved || (p.Style != "" && !(p.In == "query" && p.Style == "form") && !(p.In != "query" && p.Style == "simple")) {
		return fmt.Errorf("unsupported parameter encoding for %q", p.Name)
	}
	switch p.Schema.Type {
	case "string", "integer", "number", "boolean":
	default:
		return fmt.Errorf("unsupported parameter type %q for %q", p.Schema.Type, p.Name)
	}
	description := p.Description
	if p.Schema.Default != nil {
		description = strings.TrimSpace(fmt.Sprintf("%s (server default: %v)", description, p.Schema.Default))
	}
	fmt.Fprintf(out, "{Name: %q, In: %q, Type: %q, Description: %q, Required: %t},\n",
		p.Name, p.In, p.Schema.Type, description, p.Required)
	return nil
}

func resolve(api *huma.OpenAPI, schema *huma.Schema) (*huma.Schema, error) {
	if schema == nil {
		return nil, fmt.Errorf("missing request schema")
	}
	if schema.Ref != "" {
		resolved := api.Components.Schemas.SchemaFromRef(schema.Ref)
		if resolved == nil || resolved.Ref != "" {
			return nil, fmt.Errorf("unresolved schema reference %q", schema.Ref)
		}
		schema = resolved
	}
	return schema, nil
}

func writeBodyFields(out *bytes.Buffer, api *huma.OpenAPI, schema *huma.Schema) error {
	schema, err := resolve(api, schema)
	if err != nil {
		return err
	}
	if schema.Type != "object" {
		return fmt.Errorf("unsupported JSON body type %q", schema.Type)
	}
	out.WriteString("BodyFields: []string{\n")
	for _, name := range slices.Sorted(maps.Keys(schema.Properties)) {
		field := schema.Properties[name]
		resolved, err := resolve(api, field)
		if err != nil {
			return err
		}
		kind := resolved.Type
		if kind == "array" {
			item, err := resolve(api, resolved.Items)
			if err != nil {
				return err
			}
			kind = "array of " + item.Type
		}
		if kind == "" {
			kind = "any JSON value"
		}
		if slices.Contains(schema.Required, name) {
			kind += ", required"
		}
		help := fmt.Sprintf("%s (%s)", name, kind)
		if len(resolved.Enum) > 0 {
			help += fmt.Sprintf(" %v", resolved.Enum)
		}
		if field.Description != "" {
			help += " " + field.Description
		}
		fmt.Fprintf(out, "%q,\n", help)
	}
	out.WriteString("},\n")
	return nil
}
